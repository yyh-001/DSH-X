/**
 * WSL 里跑的那半截启动器。
 *
 * 为什么要有这个脚本：WSL 实例不是 Windows 上的一个普通子进程。wsl.exe 只是
 * 一扇门，门后面还有 bash、dsh、以及 WSL 自己的进程树；从 Windows 直接 taskkill
 * 只能杀掉门，门后面的 dsh 可能继续占着端口。启动、停止、状态、收遗留进程都放在
 * 同一个脚本里，让「谁写的 pidfile 谁负责收尸」这件事只有一个实现。
 *
 * 首版只支持 wrapper（前台进程）模式：脚本自己 exec dsh，wsl.exe 的输出就是
 * dsh 的输出，Windows 侧照旧用 READY_RE 认端口。systemd 模式留到后面再加。
 */
const scriptLines = [
  "#!/usr/bin/env bash",
  "set -u",
  "",
  "action=\"${1:-}\"",
  "if [ -n \"$action\" ]; then shift; fi",
  "",
  "# 状态目录固定放在 Linux 用户自己的 HOME 下，不跟 DSH_HOME 走：",
  "# 同一个 HOME 下可能有好几个 DSH_HOME，每个实例的 pidfile 不能混。",
  "state_dir=\"${DSH_X_WSL_STATE_DIR:-$HOME/.dsh-x}\"",
  "run_dir=\"$state_dir/run\"",
  "mkdir -p \"$run_dir\"",
  "",
  "expand_home() {",
  "  case \"$1\" in",
  "    \"~\") printf '%s' \"$HOME\" ;;",
  "    \"~/\"*) p=\"$1\"; printf '%s/%s' \"$HOME\" \"${p#\\~/}\" ;;",
  "    *) printf '%s' \"$1\" ;;",
  "  esac",
  "}",
  "",
  "# 进程身份 = PID + 启动时刻。只认 PID 不够：WSL 重启后 PID 从头分配，",
  "# 崩溃留下的 pidfile 指向的可能是别人的进程。exec 不改启动时刻，所以脚本",
  "# 自己 $$ 的值就是之后 dsh 本体的值。",
  "proc_start() {",
  "  if [ -r \"/proc/$1/stat\" ]; then",
  "    sed 's/^.*) //' \"/proc/$1/stat\" 2>/dev/null | cut -d' ' -f20",
  "    return 0",
  "  fi",
  "  ps -o lstart= -p \"$1\" 2>/dev/null | tr -s ' ' | sed 's/^ //;s/ $//'",
  "}",
  "",
  "meta_get() {",
  "  sed -n \"s/^$2=//p\" \"$1\" 2>/dev/null | head -n 1",
  "}",
  "",
  "# 记录里的 PID 还活着、而且还是当初那个进程（启动时刻对得上）才算数。",
  "same_proc() {",
  "  [ -n \"$1\" ] || return 1",
  "  kill -0 \"$1\" 2>/dev/null || return 1",
  "  [ -z \"$2\" ] && return 0",
  "  [ \"$(proc_start \"$1\")\" = \"$2\" ]",
  "}",
  "",
  "stop_pid() {",
  "  kill -TERM \"$1\" 2>/dev/null || true",
  "  n=0",
  "  while [ \"$n\" -lt 50 ]; do",
  "    kill -0 \"$1\" 2>/dev/null || return 0",
  "    sleep 0.1",
  "    n=$((n + 1))",
  "  done",
  "  kill -KILL \"$1\" 2>/dev/null || true",
  "}",
  "",
  "# 清理 run 目录：死掉的、PID 已被复用的记录直接删。带上 Profile 和 DSH_HOME 时，",
  "# 还会停掉同一个 Profile + DSH_HOME 上仍活着、但不在保留名单里的 dsh——",
  "# DSH-X 崩溃或被强杀时没人跑 stop，pidfile 和 dsh 都会留下；实例 id 每次启动",
  "# 都是新的，按 id 永远找不回它们。不收的话老 dsh 继续占着上次的端口，下一次",
  "# 启动只能换端口，同一个 Profile 上就跑着两份 dsh。保留名单是 Windows 侧还在",
  "# 管着的实例 id；没有 meta 的（老脚本写的）认不出归属，不碰。",
  "reap_records() {",
  "  want_profile=\"$1\"",
  "  want_home=\"$2\"",
  "  shift 2",
  "  for f in \"$run_dir\"/*.pid; do",
  "    [ -f \"$f\" ] || continue",
  "    other=\"${f##*/}\"",
  "    other=\"${other%.pid}\"",
  "    meta=\"$run_dir/$other.meta\"",
  "    opid=\"$(cat \"$f\" 2>/dev/null || true)\"",
  "    ostart=\"\"",
  "    if [ -f \"$meta\" ]; then ostart=\"$(meta_get \"$meta\" start)\"; fi",
  "    if ! same_proc \"$opid\" \"$ostart\"; then",
  "      rm -f \"$f\" \"$meta\" \"$run_dir/$other.stop\"",
  "      continue",
  "    fi",
  "    [ -n \"$want_profile\" ] || continue",
  "    [ -f \"$meta\" ] || continue",
  "    [ \"$(meta_get \"$meta\" profile)\" = \"$want_profile\" ] || continue",
  "    [ \"$(meta_get \"$meta\" home)\" = \"$want_home\" ] || continue",
  "    keep=0",
  "    for k in ${@+\"$@\"}; do",
  "      if [ \"$k\" = \"$other\" ]; then keep=1; fi",
  "    done",
  "    [ \"$keep\" = 1 ] && continue",
  "    echo \"dsh-x: 发现上次遗留的 dsh（PID $opid，Profile $want_profile），先停掉它\" >&2",
  "    stop_pid \"$opid\"",
  "    rm -f \"$f\" \"$meta\" \"$run_dir/$other.stop\"",
  "  done",
  "  # 停止标记只在「stop 比 start 先到」时留下；start 一直没来就会剩着，十分钟后清。",
  "  find \"$run_dir\" -maxdepth 1 -name '*.stop' -mmin +10 -exec rm -f {} + 2>/dev/null || true",
  "}",
  "",
  "case \"$action\" in",
  "  start)",
  "    id=\"${1:?missing instance id}\"",
  "    profile=\"${2:?missing profile}\"",
  "    dsh_home=\"${3:-}\"",
  "    workdir=\"${4:-}\"",
  "    port=\"${5:?missing port}\"",
  "    dsh_cmd=\"${6:-dsh}\"",
  "    shift 6 || true",
  "    if [ -z \"$dsh_home\" ]; then dsh_home=\"$HOME/.dsh\"; fi",
  "    dsh_home=\"$(expand_home \"$dsh_home\")\"",
  "    export DSH_HOME=\"$dsh_home\"",
  "    if [ -n \"$workdir\" ]; then",
  "      workdir=\"$(expand_home \"$workdir\")\"",
  "      cd \"$workdir\" || { echo \"dsh-x: workdir 不存在：$workdir\" >&2; exit 66; }",
  "    else",
  "      cd \"$dsh_home\" 2>/dev/null || cd \"$HOME\" || exit 66",
  "    fi",
  "    pidfile=\"$run_dir/$id.pid\"",
  "    metafile=\"$run_dir/$id.meta\"",
  "    stopfile=\"$run_dir/$id.stop\"",
  "    # 启动时只清死记录，不杀活进程：杀不杀要看 Windows 侧还管着哪些实例，",
  "    # 那份名单只有启动器知道，由它在挑端口前先调 reap。",
  "    reap_records \"\" \"\"",
  "    if [ -f \"$pidfile\" ]; then",
  "      old_pid=\"$(cat \"$pidfile\" 2>/dev/null || true)\"",
  "      if [ -n \"$old_pid\" ] && kill -0 \"$old_pid\" 2>/dev/null; then",
  "        echo \"dsh-x: 这个 WSL 实例已经在运行（PID $old_pid）\" >&2",
  "        exit 0",
  "      fi",
  "      rm -f \"$pidfile\"",
  "    fi",
  "    # meta 先于 pidfile 落盘：pidfile 出现时归属信息一定已经在了，收尸那边不会误判成老脚本。",
  "    {",
  "      printf 'profile=%s\\n' \"$profile\"",
  "      printf 'home=%s\\n' \"$dsh_home\"",
  "      printf 'port=%s\\n' \"$port\"",
  "      printf 'start=%s\\n' \"$(proc_start $$)\"",
  "    } > \"$metafile\"",
  "    echo $$ > \"$pidfile\"",
  "    # 先写 pidfile、再看停止标记；stop 那边反过来先立标记、再读 pidfile。",
  "    # 两边各自「先写后读」，点了启动马上点停止时至少有一边能看见对方：",
  "    # 要么 stop 读到 PID 去杀，要么这里看到标记自己退出，dsh 不会漏在 WSL 里。",
  "    if [ -f \"$stopfile\" ]; then",
  "      rm -f \"$pidfile\" \"$metafile\" \"$stopfile\"",
  "      echo \"dsh-x: 启动前已收到停止请求，不再启动 dsh\" >&2",
  "      exit 0",
  "    fi",
  "    echo \"dsh-x: 启动 $dsh_cmd $profile --host 127.0.0.1 --port $port\"",
  "    # exec 很关键：pidfile 里的 PID 必须就是 dsh 本体的 PID，停止时才能精确杀。",
  "    exec \"$dsh_cmd\" \"$profile\" --host 127.0.0.1 --port \"$port\" --no-open ${@+\"$@\"}",
  "    ;;",
  "  stop)",
  "    id=\"${1:?missing instance id}\"",
  "    port=\"${2:-}\"",
  "    pidfile=\"$run_dir/$id.pid\"",
  "    metafile=\"$run_dir/$id.meta\"",
  "    stopfile=\"$run_dir/$id.stop\"",
  "    : > \"$stopfile\"",
  "    pid=\"\"",
  "    if [ -f \"$pidfile\" ]; then pid=\"$(cat \"$pidfile\" 2>/dev/null || true)\"; fi",
  "    start_mark=\"\"",
  "    if [ -f \"$metafile\" ]; then start_mark=\"$(meta_get \"$metafile\" start)\"; fi",
  "    if same_proc \"$pid\" \"$start_mark\"; then stop_pid \"$pid\"; fi",
  "    rm -f \"$pidfile\" \"$metafile\"",
  "    # 读到了 PID 说明 start 已经过了看标记那一步，标记没用了；",
  "    # 没读到就留着，让还在路上的 start 看见后自己退出。",
  "    if [ -n \"$pid\" ]; then rm -f \"$stopfile\"; fi",
  "    # pidfile 丢了（例如 Windows 侧被杀）时，按端口兜底收一次。只在 pid 不可用时做，",
  "    # 避免误杀端口复用后的新进程。",
  "    if [ -z \"$pid\" ] && [ -n \"$port\" ] && command -v fuser >/dev/null 2>&1; then",
  "      fuser -k -TERM \"${port}/tcp\" 2>/dev/null || true",
  "    fi",
  "    exit 0",
  "    ;;",
  "  reap)",
  "    profile=\"${1:?missing profile}\"",
  "    dsh_home=\"${2:-}\"",
  "    shift 2 || shift $#",
  "    if [ -z \"$dsh_home\" ]; then dsh_home=\"$HOME/.dsh\"; fi",
  "    dsh_home=\"$(expand_home \"$dsh_home\")\"",
  "    reap_records \"$profile\" \"$dsh_home\" ${@+\"$@\"}",
  "    exit 0",
  "    ;;",
  "  status)",
  "    id=\"${1:?missing instance id}\"",
  "    pidfile=\"$run_dir/$id.pid\"",
  "    if [ -f \"$pidfile\" ]; then",
  "      pid=\"$(cat \"$pidfile\" 2>/dev/null || true)\"",
  "      if [ -n \"$pid\" ] && kill -0 \"$pid\" 2>/dev/null; then",
  "        echo \"running:$pid\"",
  "        exit 0",
  "      fi",
  "    fi",
  "    echo \"stopped\"",
  "    exit 1",
  "    ;;",
  "  *)",
  "    echo \"dsh-x: 未知操作：$action\" >&2",
  "    exit 64",
  "    ;;",
  "esac"
]

export const WSL_AGENT_SCRIPT = scriptLines.join('\n')
